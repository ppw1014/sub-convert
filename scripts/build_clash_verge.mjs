import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = 'dockerfiles/sub/conf/loyalsoldier_whitelist.ini';
const rules = [];
const providers = {};
const seen = new Set();

for (const line of fs.readFileSync(path.join(root, source), 'utf8').split(/\r?\n/)) {
  const match = line.match(/^ruleset=([^,]+),(.+)$/);
  if (!match) continue;
  const [, policy, body] = match;
  if (!['DIRECT', 'PROXY', 'REJECT', 'GOOGLE-AI'].includes(policy)) {
    throw new Error(`Unsupported policy: ${policy}`);
  }

  let rule;
  const remote = body.match(/^clash-(classic|domain|ipcidr):(https:\/\/[^,]+),(\d+)$/);
  if (remote) {
    const [, kind, url, interval] = remote;
    const name = path.basename(new URL(url).pathname, '.txt');
    if (providers[name]) throw new Error(`Duplicate provider: ${name}`);
    providers[name] = {
      type: 'http',
      behavior: kind === 'classic' ? 'classical' : kind,
      url,
      path: `./providers/sub-convert/${name}.yaml`,
      interval: Number(interval),
    };
    rule = `RULE-SET,${name},${policy}`;
  } else if (body.startsWith('[]')) {
    const inline = body.slice(2);
    // Logical rules contain nested commas; preserve the expression intact.
    if (/^(AND|OR|NOT),/.test(inline)) {
      rule = `${inline},${policy}`;
    } else if (inline.endsWith(',no-resolve')) {
      rule = `${inline.slice(0, -11)},${policy},no-resolve`;
    } else {
      rule = `${inline},${policy}`;
    }
  } else {
    throw new Error(`Unsupported ruleset: ${body}`);
  }
  if (!seen.has(rule)) {
    seen.add(rule);
    rules.push(rule);
  }
}
if (rules.at(-1) !== 'MATCH,PROXY') throw new Error('Missing proxy fallback');

// This function runs in Clash Verge's JavaScript engine, without Node APIs.
function main(config) {
  const nodes = config.proxies || [];
  // The optional local provider holds credentials outside this repository.
  const googleProvider = 'bwg-jp';
  const providers = config['proxy-providers'] || {};
  const uses = Object.keys(providers).filter(name => name !== googleProvider);
  const names = [...new Set(nodes.map(node => node.name))];
  if (!names.length && !uses.length) throw new Error('Subscription contains no nodes');
  const automatic = nodes.filter(node => !['socks5', 'http'].includes(node.type)).map(node => node.name);
  const auto = {
    name: 'AUTO',
    type: 'url-test',
    proxies: automatic.length ? automatic : names,
    url: 'https://www.gstatic.com/generate_204',
    interval: 300,
    tolerance: 50,
    lazy: true,
  };
  const selected = { name: 'PROXY', type: 'select', proxies: [...names, 'AUTO', 'DIRECT'] };
  if (uses.length) {
    auto.use = uses;
    selected.use = uses;
  }
  const google = providers[googleProvider]
    ? { name: 'GOOGLE-AI', type: 'select', use: [googleProvider] }
    : { name: 'GOOGLE-AI', type: 'select', proxies: ['PROXY'] };
  config['proxy-groups'] = [selected, auto, google];
  config.rules = SUB_CONVERT.rules;
  config['rule-providers'] = SUB_CONVERT.providers;
  config.profile = { ...(config.profile || {}), 'store-selected': true };
  return config;
}

const output = path.join(root, 'generated/clash-verge.js');
const script = `// Generated by scripts/build_clash_verge.mjs. Do not edit.\n// Source: ${source}\nconst SUB_CONVERT = ${JSON.stringify({ rules, providers }, null, 2)};\n\n${main.toString()}\n`;
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, script);

for (const copy of [
  'subweb/public/conf/loyalsoldier_whitelist.ini',
  'subconverter/base/config/loyalsoldier_whitelist.ini',
  'dockerfiles/subconverter/config/loyalsoldier_whitelist.ini',
]) {
  fs.copyFileSync(path.join(root, source), path.join(root, copy));
}
console.log(`Generated ${rules.length} Clash Verge rules and ${Object.keys(providers).length} providers; synchronized INI copies`);
